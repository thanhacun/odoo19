"""Load the guides that installed modules ship in <module>/guides/<category>/.

Layout (built from Markdown by documentation/guides/tools/build.py):
    <module>/guides/<category>/_category.md      category page (front matter: title, order, roles, menu, replaces)
    <module>/guides/<category>/<sub>/...         sub-categories nest to any depth; key = path from guides/
    <module>/guides/<category>/NN-name.md|.html  page source / the HTML Odoo imports
    <module>/guides/<category>/img/*.png         screenshots used by the page
    <module>/guides/_roles.json                  reader roles the module's pages use (code, name, groups)
Page key = "<category>/<NN-name>"; a category folder may exist in several modules, only one of
them holds its _category.md.

Runs when the registry loads (module install/upgrade, restart) for every module whose guide files
or version changed, and on demand (sync). Import rules are those of kderp_import_page: nothing is
overwritten, a changed page becomes a change request. Where the system parameter
kdvn_knowledge.guides_auto_approve is set (dev), the requests are approved at once, except for
pages edited in Odoo meanwhile.
"""
import base64
import glob
import hashlib
import json
import logging
import os
import re

from odoo import _, api, fields, models, tools
from odoo.exceptions import AccessError
from odoo.modules.module import get_module_path
from odoo.tools import html_escape

_logger = logging.getLogger(__name__)

ROOT_KEY = 'user-guides'
PARAM_AUTO_APPROVE = 'kdvn_knowledge.guides_auto_approve'
PARAM_SIGNATURE = 'kdvn_knowledge.guides_sig.'
LOCK_KEY = 7340211
HEADER_RE = re.compile(r'^<!-- generated by [^>]*-->\n')
FIELD_RE = re.compile(r'\{\{field:([\w.]+)\.(\w+)\}\}')
GUIDE_RE = re.compile(r'\{\{guide:([\w\-/]+)(?:\|([^}]*))?\}\}')


def read_front_matter(path):
    """(front matter dict, text after it) of a guide source file."""
    with open(path, encoding='utf-8') as f:
        text = f.read()
    meta = {}
    m = re.match(r'^---\n(.*?)\n---\n', text, re.S)
    if m:
        for line in m.group(1).splitlines():
            if ':' not in line:
                continue
            k, v = line.split(':', 1)
            v = v.split('#', 1)[0].strip()
            if v.startswith('[') and v.endswith(']'):
                v = [x.strip() for x in v[1:-1].split(',') if x.strip()]
            meta[k.strip()] = v
        text = text[m.end():]
    return meta, text


class KnowledgeGuideLoader(models.AbstractModel):
    _name = 'kderp.knowledge.loader'
    _description = 'Guide loader (module guides folders)'

    # ------------------------------------------------------------------
    @api.model
    def _register_hook(self):
        super(KnowledgeGuideLoader, self)._register_hook()
        if tools.config['test_enable']:
            return
        # Same cursor as the module loading: an upgrade is not committed yet, and a separate cursor
        # would not see the new module versions. The savepoint keeps a failure from breaking the load.
        try:
            with self.env.cr.savepoint():
                for line in self._sync():
                    _logger.info('Guides: %s', line)
        except Exception:
            _logger.exception('Guides could not be loaded from the modules')

    @api.model
    def sync(self, force=False):
        """Reload the guides of the installed modules now (Knowledge managers). Returns log lines."""
        if not self.env.user.has_group('document_page.group_document_manager'):
            raise AccessError(_('Only Knowledge managers can reload guides.'))
        return self._sync(force)

    # ------------------------------------------------------------------
    @api.model
    def _guide_modules(self):
        """[(module name, version, guides folder)] of installed modules that have a guides folder."""
        out = []
        for mod in self.env['ir.module.module'].search([('state', '=', 'installed')], order='name'):
            path = get_module_path(mod.name, display_warning=False)
            folder = path and os.path.join(path, 'guides')
            if folder and os.path.isdir(folder):
                out.append((mod.name, mod.latest_version or '', folder))
        return out

    @api.model
    def _guide_dirs(self, folder):
        """[(directory, key)] of every folder below <module>/guides, parents first. Key = path from guides/."""
        out = []
        for root, dirs, _files in os.walk(folder):
            dirs[:] = sorted(d for d in dirs if d != 'img' and not d.startswith(('.', '_')))
            rel = os.path.relpath(root, folder)
            if rel != '.':
                out.append((root, rel.replace(os.sep, '/')))
        return out

    @api.model
    def _signature(self, version, folder):
        digest = hashlib.sha1(version.encode('utf-8'))
        for root, _dirs, files in sorted(os.walk(folder)):
            for name in sorted(files):
                if name.endswith('.pyc'):
                    continue
                path = os.path.join(root, name)
                digest.update(os.path.relpath(path, folder).encode('utf-8'))
                with open(path, 'rb') as f:
                    digest.update(f.read())
        return digest.hexdigest()

    @api.model
    def _sync(self, force=False):
        self.env.cr.execute('SELECT pg_try_advisory_xact_lock(%s)', [LOCK_KEY])
        if not self.env.cr.fetchone()[0]:
            return ['another process is loading the guides']
        Param = self.env['ir.config_parameter'].sudo()
        todo = []
        for name, version, folder in self._guide_modules():
            sig = self._signature(version, folder)
            if force or Param.get_param(PARAM_SIGNATURE + name) != sig:
                todo.append((name, folder, sig))
        if not todo:
            return []

        lines, categories, pages = [], [], []
        for name, folder, _sig in todo:
            lines.extend(self._load_roles(name, folder))
            for cat_dir, key in self._guide_dirs(folder):
                cat_file = os.path.join(cat_dir, '_category.md')
                if os.path.isfile(cat_file):
                    meta, _body = read_front_matter(cat_file)
                    categories.append({
                        'key': key, 'type': 'category', 'parent_key': os.path.dirname(key) or ROOT_KEY,
                        'title': meta.get('title') or key.split('/')[-1],
                        'sequence': int(meta.get('order') or 10),
                        'roles': meta.get('roles') or [], 'menu_xmlid': meta.get('menu') or '',
                        'replaces': meta.get('replaces') or []})
                for md in sorted(glob.glob(os.path.join(cat_dir, '*.md'))):
                    base = os.path.basename(md)
                    if base.startswith('_') or base.count('.') > 1:
                        continue   # _category.md, translations like page.vi.md
                    pages.append((name, key, md))

        Page = self.env['document.page']
        # Parents before children, also across modules (e-approval from one module, e-approval/peak-time from another)
        categories.sort(key=lambda p: (p['key'].count('/'), p['key']))
        batch_keys = {p['key']: p['title'] for p in categories}
        for payload in categories:
            parent = payload['parent_key']
            if parent != ROOT_KEY and not (parent in batch_keys or Page.kderp_page_by_key(parent)):
                lines.append('category %-30s SKIPPED: parent "%s" not found' % (payload['key'], parent))
                continue
            res = Page._kderp_import_page(payload)
            lines.append('category %-30s %s%s' % (payload['key'], res['status'],
                                                 res.get('renamed_from') and ' (renamed from %s)' % res['renamed_from'] or ''))
        loaded = [self._read_page(name, cat, md) for name, cat, md in pages]
        batch_keys.update({p['key']: p['title'] for p in loaded if p})
        failed = set()
        for payload in loaded:
            if not payload:
                continue
            parent = payload['parent_key']
            if not (parent in batch_keys or Page.kderp_page_by_key(parent)):
                lines.append('page     %-30s SKIPPED: category "%s" not found' % (payload['key'], parent))
                failed.add(payload['module'])
                continue
            self._resolve_placeholders(payload, batch_keys)
            res = Page._kderp_import_page(payload)
            note = ''
            if res['status'] in ('created', 'updated') and Param.get_param(PARAM_AUTO_APPROVE):
                if res.get('edited_in_odoo'):
                    note = ' (left pending: page was edited in Odoo)'
                else:
                    self._auto_approve(res['id'])
                    note = ' (approved)'
            if res.get('renamed_from'):
                note = ' (renamed from %s)%s' % (res['renamed_from'], note)
            lines.append('page     %-30s %s%s' % (payload['key'], res['status'], note))
        for name, _folder, sig in todo:
            if name not in failed:
                Param.set_param(PARAM_SIGNATURE + name, sig)
        return lines

    @api.model
    def _load_roles(self, module, folder):
        """Create the reader roles of <folder>/_roles.json and link their groups.

        File: a list of {code, name, groups: [xml ids]}. A missing role is created; a role that exists
        keeps its name and only gains groups (nothing is removed). A group that does not exist on this
        site is skipped, so a module can name groups of modules that are not installed.
        """
        path = os.path.join(folder, '_roles.json')
        if not os.path.isfile(path):
            return []
        with open(path, encoding='utf-8') as f:
            entries = json.load(f)
        Role = self.env['kderp.knowledge.role'].sudo()
        lines = []
        for entry in entries:
            code = (entry.get('code') or '').strip()
            if not code:
                continue
            groups = self.env['res.groups']
            for xml_id in entry.get('groups') or []:
                groups |= self.env.ref(xml_id, raise_if_not_found=False) or self.env['res.groups']
            role = Role.search([('code', '=', code)], limit=1)
            status = 'exists'
            if not role:
                role = Role.create({'code': code, 'name': entry.get('name') or code})
                status = 'created'
            new = groups - role.group_ids
            if new:
                role.write({'group_ids': [(4, g.id) for g in new]})
                status += ', +%d group(s)' % len(new)
            lines.append('role     %-30s %s' % (code, status))
        return lines

    @api.model
    def _read_page(self, module, category, md_path):
        """Payload of one page from its .md (front matter) and .html (built), or None."""
        html_path = md_path[:-3] + '.html'
        if not os.path.isfile(html_path):
            _logger.warning('Guide %s has no .html: run documentation/guides/tools/build.py', md_path)
            return None
        meta, _body = read_front_matter(md_path)
        with open(html_path, encoding='utf-8') as f:
            html = HEADER_RE.sub('', f.read()).rstrip('\n')
        name = os.path.basename(md_path)[:-3]
        return {
            'module': module, 'key': '%s/%s' % (category, name), 'type': 'content', 'parent_key': category,
            'title': meta.get('title') or name, 'sequence': int(meta.get('order') or 10),
            'roles': meta.get('roles') or [], 'html': html, 'replaces': meta.get('replaces') or [],
            'source_path': '%s/guides/%s/%s' % (module, category, os.path.basename(md_path)),
            '_folder': os.path.dirname(md_path),
        }

    @api.model
    def _resolve_placeholders(self, payload, batch_keys):
        """{{field:model.field}} -> label; {{guide:key|text}} -> link when that page exists; images; hash."""
        Page = self.env['document.page']
        labels = {}

        def field_label(m):
            model, field = m.group(1), m.group(2)
            if model not in labels:
                labels[model] = self.env[model].with_context(lang='en_US').fields_get(attributes=['string']) \
                    if model in self.env else {}
            return html_escape(labels[model].get(field, {}).get('string', field))

        def guide_link(m):
            key, text = m.group(1), (m.group(2) or '').strip()
            page = Page.with_context(active_test=False).kderp_page_by_key(key)
            if not text:
                text = batch_keys.get(key) or page.name or key.split('/')[-1]
            if key in batch_keys or page:
                return '<a href="/kderp/guide/%s">%s</a>' % (key, html_escape(text))
            return html_escape(text)

        html = GUIDE_RE.sub(guide_link, FIELD_RE.sub(field_label, payload['html']))
        folder = payload.pop('_folder')
        images = {}
        for src in sorted(set(re.findall(r'<img[^>]*\ssrc="([^"]+)"', html))):
            if re.match(r'^(https?:|/|data:)', src):
                continue
            with open(os.path.join(folder, src), 'rb') as f:
                images[src] = base64.b64encode(f.read()).decode()
        digest = hashlib.sha1()
        for part in [payload['title'], ','.join(payload['roles']), html] + \
                [k + hashlib.sha1(base64.b64decode(v)).hexdigest() for k, v in sorted(images.items())]:
            digest.update(part.encode('utf-8'))
        payload.update(html=html, images=images, source_hash=digest.hexdigest())

    @api.model
    def _auto_approve(self, page_id):
        """Approve the pending imported change requests of a page (dev: no reviewer needed)."""
        History = self.env['document.page.history']
        pending = History.search([('page_id', '=', page_id), ('state', 'in', ('draft', 'to approve')),
                                  ('kderp_import_hash', '!=', False)])
        if pending:
            pending.write({'state': 'approved', 'approved_date': fields.Datetime.now(),
                           'approved_uid': self.env.uid})
            self.env['document.page'].browse(page_id)._compute_history_head()
